"""Triton fused NSF SineGen (frame-domain phase accumulation).

Replaces the ~6-8 small elementwise kernels of the sample-domain / frame-domain
sine generation chain (rad2 compute + fmod + cumsum + pad + reshape + sin + uv
+ noise_amp*noise) with a single Triton kernel, removing launch overhead and
letting the enclosing torch.compile CUDA graph stay compact.

Numerical contract: bit-level equivalence with the frame-domain reference
``Generator.fast_sinegen`` in usvc/backends/sovits/model.py for fp32 inputs.
Key subtleties (verified empirically against torch 2.11 + triton 3.6):

- ``tl.sin`` is bit-exact with ``torch.sin`` for fp32 (same libdevice sinf).
- ``x % 1.0`` is bit-exact with ``torch.remainder(x, 1.0)`` for fp32.
- ``torch.cumsum(rad*upp, dim=1)`` on [B, T, dim] dispatches to
  ``tensor_kernel_scan_outer_dim`` which is a *sequential* per-(b,d) column
  scan (``acc = acc + val``), NOT a tree scan. ``tl.cumsum`` is a tree scan
  and differs (maxdiff ~4e-4 for T=860), so this kernel keeps a sequential
  T-loop with a loop-carried accumulator to stay bit-exact.

Noise and random initial phase are generated by the caller in PyTorch (fixed
seed reproducible) and passed in; the kernel only fuses the ``noise_amp*noise``
scale so numerics match the eager reference exactly. If ``rand_ini``/``noise``
are None, zeros are used (deterministic, no random component).

Custom op registration mirrors usvc/_triton/dwconv1d.py so torch.compile can
trace through it (Meta + CUDA impls only; inference-only, no autograd).
"""
from __future__ import annotations

import numpy as np
import torch

from ._compat import _HAS_TRITON

if _HAS_TRITON:
    import triton
    import triton.language as tl
else:
    # 无 triton 环境: no-op jit stub（kernel 定义不报错, 实际走 torch fallback）
    class _TritonStub:
        @staticmethod
        def jit(fn=None, **kw):
            if fn is None:
                return lambda f: f
            return fn
    triton = _TritonStub()
    tl = None

__all__ = ["fused_sinegen", "_fused_sinegen_pytorch", "triton_available"]


@triton.jit
def _sinegen_kernel(
    f0_ptr, rand_ini_ptr, noise_ptr, out_ptr,
    T, L,
    sr, sine_amp, noise_std,
    upp: tl.constexpr, dim: tl.constexpr,
    BLOCK_S: tl.constexpr, S_BLOCKS: tl.constexpr,
    HAS_RAND: tl.constexpr, HAS_NOISE: tl.constexpr,
):
    """Frame-domain sinegen: out[b, t*upp+s, d] = sin(2π·phase)*sa*uv + n_amp*noise.

    phase = cumsum_{t'<t}(rad*upp) + rad*(s+1) + rand_ini[b,d],  rad=(f0_harm/sr)%1,
    f0_harm = f0[b,t]*(d+1), uv = f0>0, n_amp = uv*ns + (1-uv)*sa/3.
    Sequential T-loop matches torch's scan_outer_dim bit-exactly (fp32).
    """
    pid = tl.program_id(0)
    sb = pid % S_BLOCKS
    rest = pid // S_BLOCKS
    d = rest % dim
    b = rest // dim

    s0 = sb * BLOCK_S
    arange = tl.arange(0, BLOCK_S)
    s = s0 + arange + 1                 # 1..upp (1-based)
    smask = s <= upp
    s_f = s.to(tl.float32)

    if HAS_RAND:
        ri = tl.load(rand_ini_ptr + b * dim + d).to(tl.float32)
    else:
        ri = 0.0

    # Sequential cumsum carrier: uniform [BLOCK_S] vector (all lanes identical,
    # avoids 0-d indexing which Triton does not support).
    acc = tl.zeros([BLOCK_S], dtype=tl.float32)
    f0_base = f0_ptr + b * T
    # out layout: [B, L, dim], L = T*upp; index (b, l, d) = b*L*dim + l*dim + d
    out_base = out_ptr + b * L * dim + d

    for t in range(T):
        f0v = tl.load(f0_base + t)
        f0f = f0v.to(tl.float32)
        # uv: f0 > 0 (torch: (f0 > 0).to(sines.dtype) after fp32 promotion)
        uv = tl.where(f0f > 0.0, 1.0, 0.0)
        # rad = (f0 * (d+1) / sr) % 1  -- fp32, same op order as torch
        rad = (f0f * (d + 1) / sr) % 1.0
        # sequential cumsum of rad*upp, bit-exact with torch scan_outer_dim.
        # Note: upp is a power of two (64/512), so rad*upp is exact; even if
        # LLVM contracts acc+rad*upp into an FMA the result is unchanged.
        v = rad * upp
        prev = acc
        acc = acc + v
        # phase = prev + rad * arange(1..upp). mul.rn/add.rn prevent LLVM
        # fp-fusion (TRITON_DEFAULT_FP_FUSION=1) from contracting to an FMA:
        # torch rounds the product and the sum separately.
        rs = tl.inline_asm_elementwise(
            "mul.rn.f32 $0, $1, $2;", "=r,r,r",
            [rad, s_f], dtype=tl.float32, is_pure=True, pack=1)
        phase = tl.inline_asm_elementwise(
            "add.rn.f32 $0, $1, $2;", "=r,r,r",
            [prev, rs], dtype=tl.float32, is_pure=True, pack=1)
        phase = phase + ri
        sine = tl.sin(phase * 2.0 * 3.141592653589793) * sine_amp
        # noise_amp = uv*noise_std + (1-uv)*sine_amp/3 (uv in {0,1}: exact)
        a = uv * noise_std
        c = (1.0 - uv) * sine_amp / 3.0
        n_amp = a + c
        t1 = sine * uv
        if HAS_NOISE:
            noise_base = noise_ptr + b * L * dim + d
            nv = tl.load(noise_base + (t * upp + s0 + arange) * dim,
                         mask=smask, other=0.0).to(tl.float32)
            t2 = tl.inline_asm_elementwise(
                "mul.rn.f32 $0, $1, $2;", "=r,r,r",
                [n_amp, nv], dtype=tl.float32, is_pure=True, pack=1)
            val = tl.inline_asm_elementwise(
                "add.rn.f32 $0, $1, $2;", "=r,r,r",
                [t1, t2], dtype=tl.float32, is_pure=True, pack=1)
        else:
            val = t1
        tl.store(out_base + (t * upp + s0 + arange) * dim, val, mask=smask)


def _fused_sinegen_triton(f0, upp, dim, sr, sine_amp, noise_std, rand_ini, noise):
    """Launch the Triton kernel (bit-exact with the pytorch fallback)."""
    B, T = f0.shape
    L = T * upp
    f0 = f0.contiguous()
    out = torch.empty((B, L, dim), device=f0.device, dtype=torch.float32)
    BLOCK_S = min(128, triton.next_power_of_2(upp))
    S_BLOCKS = triton.cdiv(upp, BLOCK_S)
    grid = (B * dim * S_BLOCKS,)
    ri = rand_ini.contiguous() if rand_ini is not None else None
    nz = noise.contiguous() if noise is not None else None
    num_warps = 4 if BLOCK_S >= 128 else 2
    _sinegen_kernel[grid](
        f0, ri, nz, out,
        T, L,
        float(sr), float(sine_amp), float(noise_std),
        upp=upp, dim=dim,
        BLOCK_S=BLOCK_S, S_BLOCKS=S_BLOCKS,
        HAS_RAND=rand_ini is not None, HAS_NOISE=noise is not None,
        num_warps=num_warps,
    )
    return out


def _fused_sinegen_pytorch(f0, upp, dim, sr, sine_amp, noise_std,
                           rand_ini=None, noise=None):
    """Pure-PyTorch fallback (frame-domain algorithm, bit-identical to the
    Triton kernel: f0 promoted to fp32, all math in fp32).

    Mathematically equivalent to ``Generator.fast_sinegen`` (sovits); for fp32
    inputs this is bit-exact with it. rand_ini [B, dim] (rand_ini[:, 0] must
    be 0) and noise [B, T*upp, dim] are caller-provided for seed reproducibility.
    """
    B, T = f0.shape
    f0 = f0.to(torch.float32)
    device = f0.device
    f0_harm = f0.unsqueeze(-1) * torch.arange(
        1, dim + 1, device=device, dtype=torch.float32)
    rad = (f0_harm / sr) % 1
    if rand_ini is None:
        rand_ini = torch.zeros(B, dim, device=device, dtype=torch.float32)
    # frame-domain phase boundary (sequential scan, same order as torch)
    frame_boundary = torch.cumsum(rad * upp, dim=1)
    prev = torch.zeros_like(frame_boundary)
    prev[:, 1:, :] = frame_boundary[:, :-1, :]
    arange = torch.arange(1, upp + 1, device=device, dtype=torch.float32)
    phase = prev.unsqueeze(2) + rad.unsqueeze(2) * arange[None, None, :, None]
    phase = phase.reshape(B, T * upp, dim) + rand_ini[:, None, :]
    sines = torch.sin(phase * 2 * np.pi) * sine_amp
    uv = (f0[:, :, None] > 0).to(sines.dtype)
    uv = uv.unsqueeze(2).expand(B, T, upp, 1).reshape(B, T * upp, 1)
    noise_amp = uv * noise_std + (1 - uv) * sine_amp / 3
    if noise is None:
        noise = torch.zeros(B, T * upp, dim, device=device, dtype=sines.dtype)
    return sines * uv + noise_amp * noise


# ---------------------------------------------------------------------------
# torch.library custom op (Dynamo-traceable, CUDA-graph capture friendly).
# Inference-only: Meta + CUDA impls, no autograd.
# ---------------------------------------------------------------------------
_registered_library = None


def _register_custom_op():
    """Register usvc::fused_sinegen once. Returns True on success."""
    global _registered_library
    if _registered_library is not None:
        return True
    try:
        from torch.library import Library, impl

        lib = Library("usvc", "FRAGMENT")
        lib.define(
            "fused_sinegen(Tensor f0, Tensor? rand_ini, Tensor? noise,"
            " int upp, int dim, float sr, float sine_amp, float noise_std)"
            " -> Tensor"
        )

        @impl(lib, "fused_sinegen", "CUDA")
        def _sg_cuda(f0, rand_ini, noise, upp, dim, sr, sine_amp, noise_std):
            return _fused_sinegen_triton(
                f0, upp, dim, sr, sine_amp, noise_std, rand_ini, noise)

        @impl(lib, "fused_sinegen", "Meta")
        def _sg_meta(f0, rand_ini, noise, upp, dim, sr, sine_amp, noise_std):
            B, T = f0.shape
            return torch.empty((B, T * upp, dim), device=f0.device,
                               dtype=torch.float32)

        _registered_library = lib
        return True
    except Exception as e:
        _registered_library = False
        print(f"[fused_sinegen] custom op 注册失败: {e}")
        return False


_register_custom_op()


def fused_sinegen(f0, upp, dim, sr, sine_amp, noise_std,
                  rand_ini=None, noise=None):
    """Fused NSF sine generation (frame-domain).

    Args:
        f0: [B, T] Hz at frame rate (fp16/fp32, CUDA).
        upp: upsample factor (frames -> samples).
        dim: harmonic count (harmonic_num + 1).
        sr: sampling rate.
        sine_amp: sine amplitude.
        noise_std: additive noise std for voiced frames.
        rand_ini: [B, dim] fp32 random initial phase (rand_ini[:, 0] must be 0);
            None -> zeros (deterministic).
        noise: [B, T*upp, dim] fp32 gaussian noise; None -> no noise term.

    Returns:
        sine_waves [B, T*upp, dim] fp32 = sines*uv + noise_amp*noise.
    """
    if _registered_library is not False and f0.is_cuda and f0.dim() == 2:
        try:
            return torch.ops.usvc.fused_sinegen(
                f0, rand_ini, noise, int(upp), int(dim),
                float(sr), float(sine_amp), float(noise_std))
        except Exception:
            pass
    return _fused_sinegen_pytorch(
        f0, upp, dim, sr, sine_amp, noise_std, rand_ini, noise)


triton_available = _HAS_TRITON
